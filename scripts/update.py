#!/usr/bin/env python3
"""Build dist/feeds-v1.json from upstream OPML + source/ overlay + state/.

  * upstream recommended/with_category/*.opml -> categories (source/categories.json)
  * upstream countries/with_category/*.opml   -> region (source/regions.json), category "news"
  * source/custom-feeds.json                  -> our additions / overrides
  * source/exclusions.json                    -> removed for good
  * state/feed-health.json                    -> canonical URL repairs, quarantine,
                                                 siteURL and language from the feed itself

Feed ids are the first 12 hex digits of SHA-1 over the ORIGINAL normalised
feed URL; canonical repairs change feedURL but never the id.

Output is deterministic; publishedAt only changes when the content does.
Python 3 standard library only.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import catalog  # noqa: E402

_PRICING = re.compile(r"\bfree\b", re.IGNORECASE)
GENERATED_NOTE = "Generated by scripts/update.py — do not edit by hand."
ATTRIBUTION = {"title": "Awesome RSS Feeds by Plenary",
               "url": "https://github.com/plenaryapp/awesome-rss-feeds",
               "license": "CC0-1.0"}


def build() -> tuple[list, list, list, dict]:
    sources = catalog.load_sources()
    state = catalog.load_state()["feeds"]
    cat_map = catalog.load_category_map()
    reg_map = catalog.load_region_map()["regions"]

    stats = {"sources": len(sources), "quarantined": 0, "repaired": 0, "mergedByCanonical": 0}
    by_key: dict[str, dict] = {}
    # Process in id order so canonical-collision merges are deterministic.
    for src in sorted(sources, key=lambda s: s["id"]):
        health = state.get(src["key"], {})
        if health.get("status") == "quarantined":
            stats["quarantined"] += 1
            continue
        url = health.get("canonicalURL") or src["feedURL"]
        if not catalog.is_http_url(url):
            url = src["feedURL"]
        if url != src["feedURL"]:
            stats["repaired"] += 1
        feed = {
            "id": src["id"],
            "title": src["title"] or health.get("feedTitle") or catalog.urlsplit(url).hostname,
            "feedURL": url,
            "siteURL": src["siteURL"] or health.get("siteURL", ""),
            "summary": src["summary"],
            "categories": set(src["categories"]),
            "regions": set(src["regions"]),
            "language": src["language"] or health.get("language", ""),
            "_custom": src["origin"] == "custom",
            "_original": src["key"] == catalog.normalise_url(url),
        }
        key = catalog.normalise_url(url)
        existing = by_key.get(key)
        if existing is None:
            by_key[key] = feed
            continue
        # Two listed URLs now resolve to the same feed: keep one entry. Prefer
        # the entry whose own URL is the canonical one, then a custom entry.
        stats["mergedByCanonical"] += 1
        keep, drop = existing, feed
        if (feed["_original"], feed["_custom"]) > (existing["_original"], existing["_custom"]):
            keep, drop = feed, existing
            by_key[key] = keep
        keep["categories"] |= drop["categories"]
        keep["regions"] |= drop["regions"]
        for f in ("siteURL", "summary", "language"):
            if not keep[f] and drop[f]:
                keep[f] = drop[f]

    used_cats, used_regions = set(), set()
    feeds = []
    for f in by_key.values():
        if f["summary"] and (f["summary"].casefold() == f["title"].casefold() or _PRICING.search(f["summary"])):
            # Syndicate never shows pricing wording in its own copy, so a
            # publisher blurb that talks about price is simply left out.
            f["summary"] = ""
        if not catalog.is_http_url(f["siteURL"] or "http://x"):
            f["siteURL"] = ""
        out = {"id": f["id"], "title": f["title"], "feedURL": f["feedURL"]}
        if f["siteURL"]:
            out["siteURL"] = f["siteURL"]
        if f["summary"]:
            out["summary"] = f["summary"]
        out["categories"] = sorted(f["categories"])
        out["regions"] = sorted(f["regions"])
        if f["language"]:
            out["language"] = f["language"]
        used_cats |= f["categories"]
        used_regions |= f["regions"]
        feeds.append(out)
    feeds.sort(key=lambda x: (x["title"].casefold(), x["id"]))

    categories = sorted(({"id": c["id"], "title": c["title"], "symbol": c["symbol"]}
                         for c in cat_map["categories"] if c["id"] in used_cats),
                        key=lambda c: c["title"].casefold())
    regions = sorted(({"id": r["id"], "title": r["title"]} for r in reg_map.values() if r["id"] in used_regions),
                     key=lambda r: r["title"].casefold())
    stats["feeds"] = len(feeds)
    return categories, regions, feeds, stats


def render(published_at: str, categories, regions, feeds) -> str:
    dump = lambda v: json.dumps(v, ensure_ascii=False, separators=(",", ":"))  # noqa: E731
    lines = ["{",
             f'"schemaVersion":1,',
             f'"generated":{dump(GENERATED_NOTE)},',
             f'"publishedAt":{dump(published_at)},',
             f'"attribution":{dump(ATTRIBUTION)},',
             f'"categories":[',
             ",\n".join(dump(c) for c in categories),
             "],",
             '"regions":[',
             ",\n".join(dump(r) for r in regions),
             "],",
             '"feeds":[',
             ",\n".join(dump(f) for f in feeds),
             "]",
             "}"]
    return "\n".join(lines) + "\n"


def main() -> int:
    categories, regions, feeds, stats = build()
    # Sanity checks: the app trusts this file.
    ids = [f["id"] for f in feeds]
    assert len(ids) == len(set(ids)), "duplicate feed ids"
    cat_ids = {c["id"] for c in categories}
    reg_ids = {r["id"] for r in regions}
    for f in feeds:
        assert f["categories"] and set(f["categories"]) <= cat_ids, f
        assert set(f["regions"]) <= reg_ids, f
        assert catalog.is_http_url(f["feedURL"]), f

    previous = catalog.read_json(catalog.DIST_PATH)
    now = dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    published_at = now
    if previous and previous.get("categories") == categories and previous.get("regions") == regions \
            and previous.get("feeds") == feeds and previous.get("attribution") == ATTRIBUTION:
        published_at = previous.get("publishedAt", now)

    text = render(published_at, categories, regions, feeds)
    json.loads(text)  # must parse
    os.makedirs(os.path.dirname(catalog.DIST_PATH), exist_ok=True)
    tmp = catalog.DIST_PATH + ".tmp"
    with open(tmp, "w", encoding="utf-8") as fh:
        fh.write(text)
    os.replace(tmp, catalog.DIST_PATH)
    print(f"wrote {os.path.relpath(catalog.DIST_PATH, catalog.ROOT)}: {stats['feeds']} feeds, "
          f"{len(categories)} categories, {len(regions)} regions, {len(text.encode()) // 1024} KB "
          f"(sources {stats['sources']}, quarantined {stats['quarantined']}, repaired {stats['repaired']}, "
          f"merged by canonical URL {stats['mergedByCanonical']}"
          f"{', unchanged' if published_at != now else ''})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
